"""Build the deterministic parameter catalog from the existing authorities.

``build_catalog(root)`` is the ONLY place that joins the three typology vocabularies:

* catalog identity  -> ``examples/catalog.yaml`` (plus every file under ``examples/typologies/``)
* generator knobs   -> ``examples/typologies/*.yaml`` ``seed_params`` / ``bounds`` and the
  ``generator:`` block
* prose             -> :mod:`hornlab_search.design.params.knobs_generators`
* defaults          -> ``registry.DEFAULT_KNOBS`` (read by ``knobs_generators``)
* hard limits       -> ``families.FAMILY_KEYS[*].lo/.hi/.kind/.choices/.section``
* search bounds     -> the config's own ``bounds:`` mapping

Everything emitted is JSON-safe, sorted and relative to the repository root, so a fresh
build is byte-identical to the committed artifact. There are no timestamps and no absolute
paths. Later lanes add ``"rows"`` / ``"native"`` to ``DOMAINS`` and their own doc modules;
this builder already resolves every config, it just refuses to fabricate knob prose for a
domain nobody has authored yet.
"""
from __future__ import annotations

from pathlib import Path

import yaml

#: Domains whose knob prose is authored. Later lanes append "rows" / "native".
#: The drift test reads this tuple, so it is the single switch for domain coverage.
DOMAINS: tuple[str, ...] = ("generators",)

CATALOG_VERSION = 1

_KIND_DOMAIN = {"generator": "generators", "rows": "rows", "native": "native"}

#: Generator-block keys a user can set and see, with their path inside ``generator:``.
_BLOCK_KNOBS = (
    ("n_anchors", ("n_anchors",)),
    ("max_wall_deg", ("max_wall_deg",)),
    ("mouth", ("mouth",)),
    ("wall_thickness_mm", ("wall_thickness_mm",)),
    ("perturb.u_max", ("perturb", "u_max")),
    ("perturb.mode", ("perturb", "mode")),
)

_VALIDATION_AUTHORITY = {
    "search": ("The `search` bounds are the search box copied from this typology's "
               "examples YAML. A design sitting on a bound is at the edge of the box the "
               "search was given; it is not evidence that the value is good."),
    "hard": ("The `hard` limits are the mesher schema limits from families.KeySpec. They "
             "exist so the mesher cannot be handed an illegal value; they are not "
             "plausibility limits and they are not recommendations."),
    "recommendation": ("Neither the search box nor the hard limit implies a recommended "
                       "value. Defaults are starting points taken from their own authority, "
                       "not recommendations."),
}

_NOTE = "GENERATED by tools/gen_param_catalog.py from hornlab_search/design/params — do not edit by hand."


def _rel(root: Path, path: Path) -> str:
    """Repository-relative POSIX path, never absolute."""
    try:
        return path.resolve().relative_to(root).as_posix()
    except ValueError:
        return path.as_posix()


def _dig(mapping: dict, path: tuple[str, ...]):
    node = mapping
    for key in path:
        if not isinstance(node, dict) or key not in node:
            return None
        node = node[key]
    return node


def _plane_role(prefix: str) -> tuple[str | None, str | None]:
    if not prefix:
        return None, None
    plane = "H" if prefix.startswith("h") else "V" if prefix.startswith("v") else None
    role = None
    if "first" in prefix:
        role = "first parent"
    elif "second" in prefix:
        role = "second parent"
    elif prefix in ("hb", "vb"):
        role = "blend parent"
    return plane, role


def _generator_types(gen: dict) -> list[str]:
    types: list[str] = []
    for key in ("profile_h", "profile_v", "blend_h", "blend_v"):
        spec = gen.get(key)
        if not isinstance(spec, dict):
            continue
        if isinstance(spec.get("type"), str):
            types.append(spec["type"])
        for sub in ("first", "second"):
            nested = spec.get(sub)
            if isinstance(nested, dict) and isinstance(nested.get("type"), str):
                types.append(nested["type"])
    rows = gen.get("rows")
    if isinstance(rows, dict) and isinstance(rows.get("type"), str):
        types.append(rows["type"])
    return sorted(set(types))


def _context_id(kind: str, types: list[str], base: str, doc) -> str:
    available = doc.contexts
    if kind != "generator":
        for candidate in (kind, "native", "generator"):
            if candidate in available:
                return candidate
        return sorted(available)[0] if available else kind
    if base in ("n", "a_deg") and "biradial" in types and "generator:biradial" in available:
        return "generator:biradial"
    if base == "a_deg" and "qtw_waveguide" in types and "generator:qtw" in available:
        return "generator:qtw"
    if base == "T" and "generator:lecleach" in available \
            and any(t in ("lecleach", "spherical_wave", "spherical_salmon") for t in types):
        return "generator:lecleach"
    if base == "max_wall_deg" and "generator:spherical_salmon" in available \
            and "spherical_salmon" in types:
        return "generator:spherical_salmon"
    # The base fields always carry the general generator meaning, even when every
    # authored override lives under a sub-context (for example rm_mm's derived QTW note).
    return "generator"


def _merged(doc, context_id: str) -> dict:
    ctx = doc.contexts.get(context_id)
    label = ctx.label if ctx is not None else doc.label
    summary = ctx.summary if ctx is not None else doc.summary
    detail = ctx.detail if ctx is not None else doc.detail
    formula = ctx.formula if ctx is not None and ctx.formula is not None else doc.formula
    physical = (ctx.physical if ctx is not None and ctx.physical else doc.physical)
    flags = set(doc.flags)
    if ctx is not None:
        flags |= set(ctx.flags)
    return {
        "label": label,
        "summary": summary,
        "detail": detail,
        "formula": formula,
        "physical": physical,
        "flags": sorted(flags),
    }


def _hard_for(base: str) -> dict:
    from .knobs_generators import family_key_spec

    spec = family_key_spec(base)
    hard = {
        "lo": None if spec is None else spec["lo"],
        "hi": None if spec is None else spec["hi"],
        "kind": None if spec is None else spec["kind"],
        "choices": None if spec is None else spec["choices"],
        "section": None if spec is None else spec["section"],
        "source": None,
        "note": ("not a mesher family key; there is no hard schema clamp for this name"
                 if spec is None else
                 "mesher schema limit for the same-named family key; the generator law "
                 "may validate the knob separately"),
    }
    if spec is not None:
        hard["source"] = {
            "file": "hornlab_search/design/families.py",
            "key": f"FAMILY_KEYS.{spec['family']}.{base}",
        }
    return hard


def _placeholder(name: str, base: str, context_id: str) -> dict:
    return {
        "knob": name,
        "base_knob": base,
        "prefix": "",
        "plane": None,
        "role": None,
        "context": context_id,
        "documented": False,
        "label": name,
        "unit": None,
        "summary": "No documentation authored for this knob name yet.",
        "detail": ("This name was found in a config but has no authored entry in the "
                   "current parameter layer. It is reported rather than guessed."),
        "formula": None,
        "physical": "Not documented in this layer.",
        "code_ref": None,
        "doc_ref": None,
        "flags": ["deferred"],
        "default": None,
        "default_source": None,
        "search": None,
        "bounds_source": None,
        "hard": _hard_for(base),
        "contexts": [],
    }


def _default_for(name: str, base: str, seed: dict, bounds: dict, gen: dict,
                 config_rel: str, doc) -> tuple[object, dict | None]:
    if name in seed:
        return seed[name], {"file": config_rel, "key": f"seed_params.{name}"}
    for block_name, path in _BLOCK_KNOBS:
        if block_name != name:
            continue
        value = _dig(gen, path)
        if value is not None:
            return value, {"file": config_rel, "key": "generator." + ".".join(path)}
    if doc is not None and doc.default is not None:
        return doc.default, {
            "file": "hornlab_search/design/generators/registry.py",
            "key": f"DEFAULT_KNOBS.{base}",
        }
    return None, None


def _knob_entries(name: str, *, seed: dict, bounds: dict, gen: dict, config_rel: str,
                  kinds: list[str], kind: str, documented: bool) -> list[dict]:
    from .knobs_generators import GENERATOR_KNOBS, split_knob

    if not documented:
        return []
    names = set(seed) | set(bounds)
    for block_name, path in _BLOCK_KNOBS:
        if _dig(gen, path) is not None:
            names.add(block_name)
        elif path[0] == "perturb" and isinstance(gen.get("perturb"), dict):
            # A perturb block exists, so its mode/clip are visible even when the config
            # relies on the generator's absence semantics (documented, never invented).
            names.add(block_name)

    out: list[dict] = []
    for knob in sorted(names):
        base, prefix = split_knob(knob)
        plane, role = _plane_role(prefix)
        doc = GENERATOR_KNOBS.get(base)
        if doc is None:
            out.append(_placeholder(knob, base, _KIND_DOMAIN.get(kind, kind)))
            continue
        context_id = _context_id(kind, kinds, base, doc)
        merged = _merged(doc, context_id)
        label = merged["label"]
        if plane:
            lowered = (f"{label[:1].lower()}{label[1:]}"
                       if len(label) > 1 and label[1].islower() else label)
            label = f"{plane}-plane {lowered}"
        if role:
            label = f"{label} ({role})"
        default, default_source = _default_for(knob, base, seed, bounds, gen, config_rel, doc)
        bound = bounds.get(knob)
        search = None
        bounds_source = None
        if isinstance(bound, dict):
            search = {
                "lo": bound.get("lo"),
                "hi": bound.get("hi"),
                "search": bool(bound.get("search", True)),
                "log": bool(bound.get("log", False)),
            }
            bounds_source = {"file": config_rel, "key": f"bounds.{knob}"}
        out.append({
            "knob": knob,
            "base_knob": base,
            "prefix": prefix,
            "plane": plane,
            "role": role,
            "context": context_id,
            "documented": True,
            "label": label,
            "unit": doc.unit,
            "summary": merged["summary"],
            "detail": merged["detail"],
            "formula": merged["formula"],
            "physical": merged["physical"],
            "code_ref": doc.code_ref,
            "doc_ref": list(doc.doc_ref),
            "flags": merged["flags"],
            "default": default,
            "default_source": default_source,
            "search": search,
            "bounds_source": bounds_source,
            "hard": _hard_for(base),
            "contexts": sorted(doc.contexts),
        })
    return out


def _kind_of(gen: dict) -> str:
    if not isinstance(gen, dict) or not gen:
        return "native"
    gname = gen.get("name")
    if gname == "grid":
        return "rows"
    if gname is not None:
        return "generator"
    return "native"


def _config_sources(root: Path) -> list[tuple[str, str, dict | None]]:
    """[(typology name, repo-relative config path, catalog entry or None)] in stable order."""
    examples = root / "examples"
    catalog_path = examples / "catalog.yaml"
    catalog = yaml.safe_load(catalog_path.read_text(encoding="utf-8")) or {}
    sources: list[tuple[str, str, dict | None]] = []
    seen_files: set[str] = set()
    for entry in catalog.get("entries") or []:
        rel = f"examples/{Path(str(entry['config'])).as_posix()}"
        seen_files.add(rel)
        sources.append((str(entry["name"]), rel, entry))
    for path in sorted((examples / "typologies").glob("*.yaml")):
        rel = _rel(root, path)
        if rel in seen_files:
            continue
        seen_files.add(rel)
        sources.append((path.stem, rel, None))
    return sources


def build_catalog(root: Path) -> dict:
    """Read the authorities and return the deterministic catalog dict."""
    root = Path(root).resolve()
    examples = root / "examples"
    typologies: dict[str, dict] = {}

    for name, config_rel, entry in _config_sources(root):
        path = root / config_rel
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        gen = data.get("generator") or {}
        kind = _kind_of(gen)
        domain = _KIND_DOMAIN[kind]
        documented = domain in DOMAINS
        family = str(data.get("family") or "")
        types = _generator_types(gen) if isinstance(gen, dict) else []
        seed = data.get("seed_params") or {}
        bounds = data.get("bounds") or {}
        brief = data.get("brief_file")
        brief_rel = None
        if brief:
            brief_rel = _rel(root, (path.parent / str(brief)))
        if entry is None:
            group = "uncatalogued"
            symmetry = "unknown"
            description = ("Config present in examples/typologies/ but not listed in "
                           "examples/catalog.yaml.")
            source_status = "uncatalogued"
            brief_tied = None
            driver_exit = None
        else:
            group = str(entry.get("group") or "uncatalogued")
            symmetry = str(entry.get("symmetry") or "unknown")
            description = str(entry.get("description") or "")
            brief_tied = entry.get("brief_tied")
            driver_exit = entry.get("driver_exit_mm")
            source_status = "catalog-brief-tied" if brief_tied else "catalog"

        knobs = _knob_entries(
            name,
            seed=seed,
            bounds=bounds,
            gen=gen if isinstance(gen, dict) else {},
            config_rel=config_rel,
            kinds=types,
            kind=kind,
            documented=documented,
        )
        # Raw bound provenance for EVERY knob in the config, authored domain or not.
        # Later lanes need the file/key even before they write prose; nothing is invented
        # here (these values are copied from the YAML ``bounds:`` mapping).
        bounds_index: dict[str, dict] = {}
        for knob in sorted(bounds):
            bound = bounds[knob]
            if not isinstance(bound, dict):
                continue
            bounds_index[knob] = {
                "file": config_rel,
                "key": f"bounds.{knob}",
                "lo": bound.get("lo"),
                "hi": bound.get("hi"),
                "search": bool(bound.get("search", True)),
                "log": bool(bound.get("log", False)),
            }
        typologies[name] = {
            "name": name,
            "group": group,
            "symmetry": symmetry,
            "description": description,
            "family": family,
            "kind": kind,
            "config_path": config_rel,
            "brief_file": brief_rel,
            "source_status": source_status,
            "documented": documented,
            "knobs": knobs,
            "knob_names": [k["knob"] for k in knobs],
            "bounds_index": bounds_index,
            "brief_tied": brief_tied,
            "driver_exit_mm": driver_exit,
        }

    return {
        "catalog_version": CATALOG_VERSION,
        "domains_covered": list(DOMAINS),
        "validation_authority": dict(_VALIDATION_AUTHORITY),
        "typologies": typologies,
    }


def catalog_json_bytes(catalog: dict) -> bytes:
    """Stable byte serialization: sorted keys, fixed indent, trailing newline."""
    import json

    text = json.dumps(catalog, sort_keys=True, indent=2, ensure_ascii=True,
                      allow_nan=False)
    return (text + "\n").encode("utf-8")


