def _fmt(value) -> str:
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        return repr(value)
    return str(value)


def _source(src: dict | None) -> str:
    if not src:
        return "—"
    return f"`{src.get('file')}` `{src.get('key')}`"


def _hard_text(hard: dict) -> str:
    if hard.get("source") is None:
        return "none (not a mesher family key)"
    return (f"lo={_fmt(hard.get('lo'))}, hi={_fmt(hard.get('hi'))}, "
            f"kind={_fmt(hard.get('kind'))}, section={_fmt(hard.get('section'))} "
            f"({_source(hard.get('source'))})")


def _knob_markdown(knob: dict) -> list[str]:
    unit = f" ({knob['unit']})" if knob.get("unit") else ""
    lines = [
        f"#### `{knob['knob']}` — {knob['label']}{unit}",
        "",
        f"- **Summary:** {knob['summary']}",
        f"- **Detail:** {knob['detail']}",
        f"- **Formula:** {('`' + knob['formula'] + '`') if knob.get('formula') else 'not stated'}",
        f"- **Physical effect:** {knob['physical']}",
        f"- **Context:** `{knob['context']}`",
        f"- **Default:** {_fmt(knob.get('default'))} (source: {_source(knob.get('default_source'))})",
    ]
    search = knob.get("search")
    if search is None:
        lines.append("- **Search bounds:** none (this is a block value, not a searched knob)")
    else:
        lines.append(
            f"- **Search bounds:** {_fmt(search.get('lo'))} .. {_fmt(search.get('hi'))} "
            f"(search={_fmt(search.get('search'))}, log={_fmt(search.get('log'))}; "
            f"source: {_source(knob.get('bounds_source'))})")
    lines.extend([
        f"- **Hard limits:** {_hard_text(knob.get('hard') or {})}",
        f"- **Code:** `{knob.get('code_ref') or '—'}`",
        f"- **Doc:** {('`' + knob['doc_ref'][0] + '` § ' + knob['doc_ref'][1]) if knob.get('doc_ref') else '—'}",
        f"- **Flags:** {', '.join(knob.get('flags') or []) or '—'}",
        "",
    ])
    return lines


def _documented_typologies(catalog: dict) -> list[dict]:
    return [catalog["typologies"][name]
            for name in sorted(catalog["typologies"])
            if catalog["typologies"][name]["documented"]]


def render_parameters_markdown(catalog: dict) -> str:
    lines = [
        "# Parameter reference",
        "",
        f"> {_NOTE}",
        "",
        f"Catalog version: {catalog['catalog_version']}  ",
        f"Domains covered: {', '.join('`' + d + '`' for d in catalog['domains_covered'])}",
        "",
        "## Validation authority",
        "",
    ]
    for key in ("search", "hard", "recommendation"):
        lines.append(f"- **{key}:** {catalog['validation_authority'][key]}")
    lines.append("")

    groups: dict[str, list[dict]] = {}
    for typ in _documented_typologies(catalog):
        groups.setdefault(typ["group"], []).append(typ)
    for group in sorted(groups):
        lines.extend([f"## Group: {group}", ""])
        for typ in sorted(groups[group], key=lambda t: t["name"]):
            lines.extend([
                f"### {typ['name']} — {typ['family']} / {typ['kind']}",
                "",
                f"- **Group:** {typ['group']}",
                f"- **Symmetry:** {typ['symmetry']}",
                f"- **Config:** `{typ['config_path']}`",
                f"- **Brief:** {('`' + typ['brief_file'] + '`') if typ.get('brief_file') else '—'}",
                f"- **Source status:** {typ['source_status']}",
                f"- **Description:** {typ['description']}",
                "",
            ])
            for knob in typ["knobs"]:
                lines.extend(_knob_markdown(knob))
    return "\n".join(lines).rstrip() + "\n"


def render_typologies_markdown(catalog: dict) -> str:
    lines = [
        "# Typology reference",
        "",
        f"> {_NOTE}",
        "",
        f"Catalog version: {catalog['catalog_version']}  ",
        f"Domains covered: {', '.join('`' + d + '`' for d in catalog['domains_covered'])}",
        "",
    ]
    for name in sorted(catalog["typologies"]):
        typ = catalog["typologies"][name]
        lines.extend([
            f"## `{name}`",
            "",
            f"- **Family:** {typ['family']}",
            f"- **Kind:** {typ['kind']}",
            f"- **Group:** {typ['group']}",
            f"- **Symmetry:** {typ['symmetry']}",
            f"- **Description:** {typ['description']}",
            f"- **Source status:** {typ['source_status']}",
            f"- **Config:** `{typ['config_path']}`",
            f"- **Brief:** {('`' + typ['brief_file'] + '`') if typ.get('brief_file') else '—'}",
            f"- **Documented:** {_fmt(typ['documented'])}",
            f"- **Knobs:** {len(typ['knobs'])}",
            "",
        ])
        if typ["knobs"]:
            lines.extend([
                "| Knob | Label | Unit | Default | Search | Hard lo | Hard hi | Summary |",
                "|---|---|---|---|---|---|---|---|",
            ])
            for knob in typ["knobs"]:
                search = knob.get("search")
                search_txt = (f"{_fmt(search.get('lo'))} .. {_fmt(search.get('hi'))}"
                              if search is not None else "—")
                hard = knob.get("hard") or {}
                lines.append(
                    f"| `{knob['knob']}` | {knob['label']} | {_fmt(knob.get('unit'))} | "
                    f"{_fmt(knob.get('default'))} | {search_txt} | {_fmt(hard.get('lo'))} | "
                    f"{_fmt(hard.get('hi'))} | {knob['summary']} |")
            lines.append("")
        else:
            lines.extend([
                "No knobs are authored for this typology in the current domains "
                f"({', '.join(catalog['domains_covered'])}). It is resolved, not fabricated.",
                "",
            ])
    return "\n".join(lines).rstrip() + "\n"
