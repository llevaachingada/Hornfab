"""Body-clearance gate for two-body (horn + enclosure) BL assemblies (risk register R16).

Boundary Lab's compiler accepts separate closed bodies without checking that they do not
intersect, and the horn mount offset is a free number. Before this gate, the horn standoff was
only inferred from bounding boxes after the fact; a 0 mm offset case
(``bl_ref_case/20261118T231100Z-assembly-62864-f62bf799``) staged with the horn's rear 3 mm
inside the enclosure's front-face plane (vertex-to-vertex minimum 0.7 mm). This module makes
the clearance an explicit, recorded verdict.

Verdict logic (conservative, cheap, no new geometry code):

* **PASS** when the axis-aligned bounding boxes of the placed horn and of every enclosure
  surface are separated by at least ``min_gap_m``. The AABB gap is a proven LOWER bound on the
  true surface-to-surface distance, so a pass is a proof, not an estimate.
* **BODY_CLEARANCE_VIOLATION** when some horn vertex lies closer than ``min_gap_m`` to some
  enclosure vertex. The vertex distance is an UPPER bound on the true distance, so this is a
  proof of violation.
* **BODY_CLEARANCE_UNPROVEN** otherwise (boxes overlap but no vertex pair is close: nested or
  interleaved bodies). Refused by default; neither proof holds, so no number is claimed.

Coordinates are metres. The horn is placed exactly as the stage runner places it:
``points * scale_factor + translation_mm / 1000`` (BL ``MeshResource.scale_to_m`` /
``translation_m``). Enclosure meshes generated by BL are already in metres.
"""
from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable, Sequence

import numpy as np

__all__ = [
    "CLEARANCE_PASS", "BODY_CLEARANCE_VIOLATION", "BODY_CLEARANCE_UNPROVEN",
    "DEFAULT_MIN_GAP_M", "ClearanceReport", "body_clearance", "aabb_gap_m",
]

CLEARANCE_PASS = "PASS"
BODY_CLEARANCE_VIOLATION = "BODY_CLEARANCE_VIOLATION"
BODY_CLEARANCE_UNPROVEN = "BODY_CLEARANCE_UNPROVEN"

#: Minimum proven horn-to-enclosure surface gap (1 mm, the R16 proposal).
DEFAULT_MIN_GAP_M = 1.0e-3


@dataclass(frozen=True)
class ClearanceReport:
    status: str
    min_gap_m: float
    aabb_gap_m: float                       # proven lower bound on the true distance
    vertex_min_distance_m: float | None     # upper bound; computed only when AABBs are close
    horn_bbox_m: tuple[tuple[float, float, float], tuple[float, float, float]]
    body_bbox_m: tuple[tuple[float, float, float], tuple[float, float, float]]
    horn_mesh: str
    body_meshes: tuple[str, ...]
    translation_mm: tuple[float, float, float]
    scale_factor: float

    @property
    def ok(self) -> bool:
        return self.status == CLEARANCE_PASS

    def to_dict(self) -> dict[str, Any]:
        return {
            "kind": "body_clearance_v1",
            "status": self.status,
            "min_gap_m": self.min_gap_m,
            "aabb_gap_m": self.aabb_gap_m,
            "vertex_min_distance_m": self.vertex_min_distance_m,
            "horn_bbox_m": [list(self.horn_bbox_m[0]), list(self.horn_bbox_m[1])],
            "body_bbox_m": [list(self.body_bbox_m[0]), list(self.body_bbox_m[1])],
            "horn_mesh": self.horn_mesh,
            "body_meshes": list(self.body_meshes),
            "translation_mm": list(self.translation_mm),
            "scale_factor": self.scale_factor,
            "bounds": "aabb_gap_m is a lower bound; vertex_min_distance_m is an upper bound",
        }


def _read_points(path: str | os.PathLike[str]) -> np.ndarray:
    import meshio

    p = Path(path)
    if not p.is_file():
        raise FileNotFoundError(f"mesh not found for clearance check: {p}")
    pts = np.asarray(meshio.read(p).points, dtype=np.float64)
    if pts.ndim != 2 or pts.shape[1] != 3 or pts.shape[0] == 0:
        raise ValueError(f"mesh {p} has no 3-D points")
    return pts


def _bbox(pts: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    return pts.min(axis=0), pts.max(axis=0)


def aabb_gap_m(a_min: Sequence[float], a_max: Sequence[float],
               b_min: Sequence[float], b_max: Sequence[float]) -> float:
    """Euclidean distance between two axis-aligned boxes (0.0 when they touch or overlap)."""
    a0, a1, b0, b1 = (np.asarray(v, dtype=np.float64) for v in (a_min, a_max, b_min, b_max))
    sep = np.maximum.reduce([b0 - a1, a0 - b1, np.zeros(3)])
    return float(np.linalg.norm(sep))


def body_clearance(
    horn_mesh: str | os.PathLike[str],
    body_meshes: Iterable[str | os.PathLike[str]],
    *,
    translation_mm: Sequence[float] = (0.0, 0.0, 0.0),
    scale_factor: float = 1.0,
    min_gap_m: float = DEFAULT_MIN_GAP_M,
) -> ClearanceReport:
    """Verdict on the gap between the placed horn and the enclosure surface meshes."""
    if not (min_gap_m > 0.0 and np.isfinite(min_gap_m)):
        raise ValueError(f"min_gap_m must be a positive finite number, got {min_gap_m!r}")
    bodies = [Path(p) for p in body_meshes]
    if not bodies:
        raise ValueError("body_clearance needs at least one enclosure surface mesh")
    t = np.asarray([float(v) for v in translation_mm], dtype=np.float64)
    if t.shape != (3,):
        raise ValueError(f"translation_mm must have 3 components, got {translation_mm!r}")
    horn_pts = _read_points(horn_mesh) * float(scale_factor) + t / 1000.0
    body_pts = np.vstack([_read_points(p) for p in bodies])
    h0, h1 = _bbox(horn_pts)
    b0, b1 = _bbox(body_pts)
    gap = aabb_gap_m(h0, h1, b0, b1)
    vertex_min: float | None = None
    if gap >= min_gap_m:
        status = CLEARANCE_PASS
    else:
        from scipy.spatial import cKDTree

        dist, _ = cKDTree(body_pts).query(horn_pts, k=1)
        vertex_min = float(dist.min())
        status = BODY_CLEARANCE_VIOLATION if vertex_min < min_gap_m else BODY_CLEARANCE_UNPROVEN

    def _t(v: np.ndarray) -> tuple[float, float, float]:
        return (float(v[0]), float(v[1]), float(v[2]))

    return ClearanceReport(
        status=status, min_gap_m=float(min_gap_m), aabb_gap_m=gap,
        vertex_min_distance_m=vertex_min,
        horn_bbox_m=(_t(h0), _t(h1)), body_bbox_m=(_t(b0), _t(b1)),
        horn_mesh=str(Path(horn_mesh)), body_meshes=tuple(str(p) for p in bodies),
        translation_mm=_t(t), scale_factor=float(scale_factor),
    )
