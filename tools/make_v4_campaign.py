"""Generate the objective-v4 copy of the 2026-10-26 campaign (briefs + typology configs).

Reads ``examples/briefs/campaign_2026-10-26/*.yaml`` and ``examples/typologies/campaign_2026-10-26/*.yaml``
and writes ``*_v4`` copies into sibling ``campaign_2026-10-26_v4/`` folders. The v3 files are never
touched. Each brief is assigned a horn CLASS (docs/research/V4_TOLERANCE_RESEARCH_2026-10-27.md s3):

* ``A`` constant-directivity waveguide: narrow side counts 2x, presence band (2.5-5.5 kHz) weighted x2,
  DI std and diagonal live;
* ``B`` loading / rollback: symmetric coverage, looser DI-slope tolerance, load term as the brief had it;
* ``C`` low-reach PA that falls off: one-sided coverage below f0, narrow side 2x, presence band x2.

The tolerances are Option A (physical) from docs/evidence/OBJECTIVE_V4_TOLERANCES.md for class A and the
proposed looser class numbers for B and C; all are owner-tunable. Every config keeps its own seed, bounds and
mesh settings: only ``name`` and ``brief_file`` change, so a v3 cell and its v4 twin differ in scoring only.

Usage::

    .venv\\Scripts\\python.exe tools\\make_v4_campaign.py [--check]

``--check`` writes nothing and exits 1 if the generated files would differ from what is on disk.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
BRIEFS_V3 = REPO / "examples" / "briefs" / "campaign_2026-10-26"
BRIEFS_V4 = REPO / "examples" / "briefs" / "campaign_2026-10-26_v4"
TYP_V3 = REPO / "examples" / "typologies" / "campaign_2026-10-26"
TYP_V4 = REPO / "examples" / "typologies" / "campaign_2026-10-26_v4"

PRESENCE_BAND = (2500.0, 5500.0, 2.0)

TOL = {
    "A": dict(cov=2.0, rip=1.0, di=0.4, dislope=9.0, flat=1.5, load=0.3, distd=2.0, diag=2.0),
    "B": dict(cov=4.5, rip=2.0, di=0.4, dislope=36.0, flat=1.5, load=0.3, distd=3.0, diag=4.5),
    "C": dict(cov=4.5, rip=2.0, di=0.4, dislope=36.0, flat=1.5, load=0.3, distd=3.0, diag=4.5),
}
CLASS_NOTE = {
    "A": "CLASS A (constant-directivity waveguide): narrow side counts 2x the wide side; DI std and the\n"
         "# diagonal term are live; the 2.5-5.5 kHz presence band is weighted x2 (owner field experience).",
    "B": "CLASS B (loading / rollback): symmetric coverage (narrowing can be the design), looser DI-slope\n"
         "# tolerance (DI rises naturally), load term as the v3 brief had it. DI std and the diagonal are live.",
    "C": "CLASS C (low-reach PA that falls off): below f0 a WIDE pattern is physics and free, a NARROW one is\n"
         "# still scored (one_sided); narrow side 2x everywhere; presence band weighted x2.",
}
#: per-class new weights; (distd, diag)
NEW_WEIGHTS = {"A": (0.5, 0.5), "B": (0.3, 0.5), "C": (0.3, 0.5)}
OBJECTIVE_EXTRA = {
    "A": "  cov_narrow_ratio: 2.0\n",
    "B": "  cov_narrow_ratio: 1.0\n",
    "C": "  cov_narrow_ratio: 2.0\n  cov_below_f0: one_sided\n",
}
#: Brief-specific overrides on top of the class: the Le Cleac'h native brief narrows by design
#: (cov 0.3, dislope 0), so its diagonal/DI-std weights stay small and presence weighting is not applied.
OVERRIDES = {
    "native_lecleach_1200_1in": {"weights": (0.0, 0.15), "presence": False},
}


def brief_class(stem: str) -> str:
    if stem.startswith("b3a_"):
        return "C"
    if stem.startswith(("b3bt_", "b3bw_", "native_lecleach")):
        return "B"
    if stem.startswith(("b1t_", "b1w_", "b2t_", "b2w_", "native_ath_core", "native_twinray")):
        return "A"
    raise SystemExit(f"make_v4_campaign: no class for brief {stem!r}; add it to brief_class()")


def make_brief(src: Path) -> str:
    stem = src.stem
    klass = brief_class(stem)
    ov = OVERRIDES.get(stem, {})
    distd, diag = ov.get("weights", NEW_WEIGHTS[klass])
    s = src.read_text(encoding="utf-8-sig")
    if "freq_weights" in s:
        raise SystemExit(f"{src.name}: already carries freq_weights; the generator would clobber it")
    s = re.sub(r"^name: (\S+)", lambda m: f"name: {m.group(1)}_v4", s, count=1, flags=re.M)
    s = re.sub(r"^description: ", "description: (objective v4) ", s, count=1, flags=re.M)
    note = ("# OBJECTIVE v4 COPY (2026-10-27, generated by tools/make_v4_campaign.py): the v3 brief with\n"
            "# tolerance-normalised scoring. The v3 brief is untouched.\n# " + CLASS_NOTE[klass] + "\n"
            "# Tolerances: docs/evidence/OBJECTIVE_V4_TOLERANCES.md (class A = Option A); class B/C numbers are\n"
            "# proposals [E] from docs/research/V4_TOLERANCE_RESEARCH_2026-10-27.md. Raw term = stored term x tolerance.\n")
    s = note + s
    if klass in ("A", "C") and ov.get("presence", True):
        lo, hi, w = PRESENCE_BAND
        s = s.replace("\nweights:\n", f"\n  freq_weights:\n    band_hz:\n      - [{lo}, {hi}, {w}]\nweights:\n", 1)
    if not re.search(r"^  load: .*$", s, re.M):
        raise SystemExit(f"{src.name}: no 'load:' weight line to anchor the new weights on")
    s = re.sub(r"^(  load: .*)$", lambda m: f"{m.group(1)}\n  distd: {distd}\n  diag: {diag}", s, count=1, flags=re.M)
    tol = TOL[klass]
    obj = ("objective:\n  version: 4\n  tolerances:\n" + "".join(f"    {k}: {v}\n" for k, v in tol.items())
           + OBJECTIVE_EXTRA[klass])
    s, n = re.subn(r"objective:\n  version: 3\n?", obj, s, count=1)
    if n != 1:
        raise SystemExit(f"{src.name}: expected an 'objective: version: 3' block")
    return s


def make_config(src: Path) -> str:
    s = src.read_text(encoding="utf-8-sig")
    m = re.search(r"^brief_file: (.+)$", s, re.M)
    if not m:
        raise SystemExit(f"{src.name}: no brief_file line")
    old = m.group(1).strip()
    stem = Path(old).stem
    s = s.replace(m.group(0), f"brief_file: ../../briefs/campaign_2026-10-26_v4/{stem}_v4.yaml", 1)
    s = re.sub(r"^name: (\S+)", lambda mm: f"name: {mm.group(1)}_v4", s, count=1, flags=re.M)
    return ("# OBJECTIVE v4 TWIN (generated by tools/make_v4_campaign.py): identical geometry, bounds and mesh\n"
            "# settings to the v3 cell of the same name; only the brief (objective v4) and the name differ.\n") + s


def build() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for src in sorted(BRIEFS_V3.glob("*.yaml")):
        out[BRIEFS_V4 / f"{src.stem}_v4.yaml"] = make_brief(src)
    for src in sorted(TYP_V3.glob("*.yaml")):
        out[TYP_V4 / f"{src.stem}_v4.yaml"] = make_config(src)
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 on drift")
    args = ap.parse_args(argv)
    files = build()
    drift = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in drift:
            print(f"drift: {p.relative_to(REPO)}")
        return 1 if drift else 0
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} files ({len(list(BRIEFS_V4.glob('*.yaml')))} briefs, "
          f"{len(list(TYP_V4.glob('*.yaml')))} configs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
